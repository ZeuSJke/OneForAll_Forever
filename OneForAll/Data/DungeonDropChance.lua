-- Returns the drop chance (number, percent) or nil; second value: the Wowhead kills when it was measured in Forever
-- (0 = number not kept), nil for a Classic chance (6.2.12-beta10); third: true when the counts were scaled (beta12)
local forever
function FLT.GetDropChance(dungeonName, bossName, itemID)
  local d = dungeonName and FLT.DUNGEON_DROP_CHANCE[dungeonName]
  local b = d and bossName and d[bossName]
  local c = b and itemID and b[itemID] or nil
  if not c then return nil end
  if not forever then
    forever = {}
    for _, r in ipairs(FLT.DUNGEON_DROP_FOREVER or {}) do forever[r[1] .. "|" .. r[2] .. "|" .. r[3]] = r end
  end
  local r = forever[dungeonName .. "|" .. bossName .. "|" .. itemID]
  return c, r and r[4], r and r[5] or nil
end
